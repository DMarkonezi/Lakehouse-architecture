#!/bin/bash
set -e
psql -v ON_ERROR_STOP=1 -U "$POSTGRES_USER" -d "$POSTGRES_DB" <<EOSQL
CREATE ROLE "$LAKE_READER_USER" LOGIN PASSWORD '$LAKE_READER_PASSWORD';
GRANT SELECT ON ALL TABLES IN SCHEMA public TO "$LAKE_READER_USER";
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT SELECT ON TABLES TO "$LAKE_READER_USER";
EOSQL
